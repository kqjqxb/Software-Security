def lab2(n: int) -> dict:
    if not 1 <= n <= len(TABLE):
        raise SystemExit(f"Номер варіанта має бути в межах 1–{len(TABLE)}")
    model, rule, anomalies, subjects, objects = TABLE[n - 1]
    return {
        "variant": n,
        "lab": 2,
        "model": f"{model}: {MODELS[model]}",
        "rule": f"{rule}: {RULES[rule]}",
        "anomalies": [f"{a}: {ANOMALIES[a]}" for a in anomalies.split()],
        "subjects": subjects,
        "objects": objects,
    }


